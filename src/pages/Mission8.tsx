import { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { Leaf, CheckCircle2 } from 'lucide-react';
import { useApp } from '../store';
import { motion, AnimatePresence } from 'motion/react';
import { MissionWrapper } from '../components/MissionWrapper';
import { MentorVideo } from '../components/MentorVideo';
import { ImageSwiper } from '../components/ui/image-swiper';

const QUESTIONS = [
  {
    id: 'morando', title: 'Onde você está morando?',
    options: [
      { text: 'Em uma metrópole futurista',      image: '/questions/fase8-morando-metropole.jpeg' },
      { text: 'Perto da natureza',                image: '/questions/fase8-morando-natureza.jpeg' },
      { text: 'Próximo à praia/mar',              image: '/questions/fase8-morando-praia.jpeg' },
      { text: 'Nômade digital pelo mundo',        image: '/questions/fase8-morando-nomade.jpeg' },
    ],
  },
  {
    id: 'companhia', title: 'Com quem você está?',
    options: [
      { text: 'Com meu(a) parceiro(a) ou grande amor', image: '/questions/fase8-companhia-casal.jpeg' },
      { text: 'Com família e filhos',                   image: '/questions/fase8-companhia-familia.jpeg' },
      { text: 'Perto de amigos próximos e comunidade',  image: '/questions/fase8-companhia-amigos.jpeg' },
      { text: 'Com meus animais de estimação',          image: '/questions/fase8-companhia-pets.jpeg' },
    ],
  },
  {
    id: 'manha', title: 'Como é sua manhã?',
    options: [
      { text: 'Acordo cedo para exercícios e meditação', image: '/questions/fase8-manha-exercicio.jpeg' },
      { text: 'Tomo café com calma lendo notícias',      image: '/questions/fase8-manha-cafe.jpeg' },
      { text: 'Já começo o dia reunido com a equipe',    image: '/questions/fase8-maha-reuniao.jpeg' },
      { text: 'Durmo até tarde e foco à noite',          image: '/questions/fase8-manha-noite.jpeg' },
    ],
  },
  {
    id: 'trabalho', title: 'Como é o ambiente e o formato do seu trabalho?',
    options: [
      { text: 'Em um escritório moderno ou laboratório', image: '/questions/fase8-trabalho-escritorio.jpeg' },
      { text: 'Híbrido/remoto de qualquer lugar',        image: '/questions/fase8-trabalho-remoto.jpeg' },
      { text: 'No campo, ao ar livre ou viajando',       image: '/questions/fase8-trabalho-campo.jpeg' },
      { text: 'No meu próprio estúdio/ateliê focado',    image: '/questions/fase8-trabalho-estudio.jpeg' },
    ],
  },
  {
    id: 'fim_dia', title: 'O que te faz sorrir no final do dia?',
    options: [
      { text: 'Saber que resolvi um problema complexo',  image: '/questions/fase8-fim-problema.jpeg' },
      { text: 'O impacto positivo que causei nas pessoas', image: '/questions/fase8-fim-impacto.jpeg' },
      { text: 'A liberdade financeira e o conforto',     image: '/questions/fase8-fim-liberdade.jpeg' },
      { text: 'Ter terminado a gravação/criação do dia', image: '/questions/fase8-fim-criacao.jpeg' },
    ],
  },
];

export default function Mission8() {
  const navigate = useNavigate();
  const { state, updateMission, addXP, completeMission } = useApp();

  const [step, setStep] = useState(0); // 0: intro, 1-5: questions, 6: letter, 7: done

  const { letter, future } = state.mission8;

  const autoGeneratedLetter = `Querido(a) eu do futuro...

Hoje, imaginei que daqui a 10 anos estarei vivendo ${future.morando?.toLowerCase() || 'em algum lugar incrível'}, e estarei acompanhado(a) ${future.companhia?.toLowerCase() || 'de quem amo'}.

Minha rotina ideal começa de uma forma bem específica: ${future.manha?.toLowerCase() || 'com bastante calma'}. Durante o dia, passo a maior parte do tempo trabalhando ${future.trabalho?.toLowerCase() || 'com meu propósito'}, e a sensação de que valeu a pena vem de ${future.fim_dia?.toLowerCase() || 'fazer o que gosto'}.

Não quero esquecer dessa visão, vou lutar por ela.
Assinado,
Eu do presente.`;

  const handleNextQ = () => {
    setStep(s => s + 1);
    addXP(10);
  };

  const handlePrevQ = () => setStep(s => s - 1);

  const handleFieldChange = (field: string, value: string) => {
    updateMission('mission8', { future: { ...future, [field]: value }, letter: '' });
  };

  const handleLetterChange = (value: string) => {
    updateMission('mission8', { letter: value });
  };

  const handleComplete = () => {
    const finalLetter = letter || autoGeneratedLetter;
    if (finalLetter.length > 10) {
      updateMission('mission8', { letter: finalLetter });
      addXP(100);
      completeMission(8);
      setStep(7);
    }
  };

  // ── Step 0: Intro (vídeo da fase + início) ───────────────────────────────
  if (step === 0) {
    return (
      <MissionWrapper
        videoTitle="A Carta para o Futuro"
        videoDescription="Respire fundo, vamos visualizar onde você quer estar daqui a 10 anos."
        videoId="missao8"
      >
        <div className="flex flex-col items-center justify-center min-h-[60vh] text-center">
          <p className="text-stone-500 max-w-sm mb-10">
            Respire fundo. Visualize onde você quer estar daqui a 10 anos.
          </p>
          <button
            onClick={() => setStep(1)}
            className="bg-[var(--color-brand-600)] text-white font-medium px-8 py-3 rounded-full hover:bg-[var(--color-brand-700)] transition-colors"
          >
            Começar →
          </button>
        </div>
      </MissionWrapper>
    );
  }

  // ── Step 7: Done ──────────────────────────────────────────────────────────
  if (step === 7) {
    return (
      <div className="flex flex-col items-center text-center max-w-md mx-auto w-full">
        <motion.div
          initial={{ scale: 0.8, opacity: 0 }}
          animate={{ scale: 1, opacity: 1 }}
          className="w-16 h-16 rounded-full bg-[var(--color-brand-50)] text-[var(--color-brand-600)] flex items-center justify-center mb-4"
        >
          <CheckCircle2 className="w-8 h-8" />
        </motion.div>
        <h2 className="font-serif text-4xl text-[var(--text-main)] mb-2">Missão concluída</h2>
        <p className="text-stone-500 mb-6">+200 XP adicionados à sua jornada</p>

        <MentorVideo
          title="Parabéns pela Jornada!"
          description="Uma mensagem especial para você."
          videoId="missao_concluida"
        />

        <button
          onClick={() => navigate('/comecar/salvar')}
          className="px-6 py-3 bg-[var(--color-brand-600)] text-white rounded-[4px] font-medium hover:bg-[var(--color-brand-700)] transition-colors inline-flex items-center gap-2"
        >
          Ver meu Resultado →
        </button>
      </div>
    );
  }

  // ── Steps 1-5: Question swipe cards ──────────────────────────────────────
  if (step >= 1 && step <= 5) {
    const qIndex = step - 1;
    const q = QUESTIONS[qIndex];
    const qImages = q.options.map(o => o.image).join(',');
    const activeText = future[q.id] || q.options[0].text;

    return (
      <div className="flex flex-col min-h-[70vh] max-w-2xl mx-auto w-full">
        {/* Context banner */}
        <div className="bg-[var(--color-brand-50)] border border-[var(--color-brand-200)] rounded-lg p-5 mb-6 flex items-start gap-3">
          <div className="bg-[var(--color-brand-100)] p-2 rounded-full text-[var(--color-brand-600)] shrink-0 mt-0.5">
            <Leaf className="w-4 h-4" />
          </div>
          <div>
            <p className="text-[var(--text-main)] text-sm leading-relaxed mb-1.5">
              Daqui a 10 anos, imagine... Responda com o coração, sem julgamentos.
            </p>
            <span className="inline-flex items-center gap-1 text-xs font-bold px-2.5 py-1 rounded-full bg-[var(--color-brand-100)] text-[var(--color-brand-700)] border border-[var(--color-brand-200)]">
              ● Arraste para explorar · Toque na carta para confirmar
            </span>
          </div>
        </div>

        {/* Progress */}
        <div className="flex gap-2 mb-6">
          {QUESTIONS.map((_, i) => (
            <div key={i} className="h-1 flex-1 rounded bg-stone-200 overflow-hidden">
              {i <= qIndex && <div className="h-full w-full bg-[var(--color-brand-500)]" />}
            </div>
          ))}
        </div>

        <AnimatePresence mode="wait">
          <motion.div
            key={step}
            initial={{ opacity: 0, x: 30 }}
            animate={{ opacity: 1, x: 0 }}
            exit={{ opacity: 0, x: -30 }}
            transition={{ duration: 0.25 }}
            className="flex-grow flex flex-col items-center"
          >
            {/* Question title */}
            <h2 className="font-serif text-2xl text-[var(--text-main)] mb-6 text-center">
              {q.title}
            </h2>

            {/* Card swiper */}
            <div className="flex flex-col items-center mb-4">
              <ImageSwiper
                images={qImages}
                cardWidth={300}
                cardHeight={420}
                onActiveIndexChange={(index) => handleFieldChange(q.id, q.options[index].text)}
                onSelect={() => { if (future[q.id]?.length > 3) handleNextQ(); }}
                overlay={
                  <AnimatePresence mode="wait">
                    <motion.div
                      key={activeText}
                      initial={{ opacity: 0, y: 8 }}
                      animate={{ opacity: 1, y: 0 }}
                      exit={{ opacity: 0, y: -8 }}
                      transition={{ duration: 0.2 }}
                      style={{
                        background: 'linear-gradient(to top, rgba(0,0,0,0.92) 0%, rgba(0,0,0,0.55) 65%, transparent 100%)',
                        padding: '3.5rem 1.25rem 1.5rem',
                        borderRadius: '0 0 0.75rem 0.75rem',
                      }}
                    >
                      <p className="text-white font-semibold text-base text-center leading-snug drop-shadow-lg">
                        {activeText}
                      </p>
                    </motion.div>
                  </AnimatePresence>
                }
              />
              <p className="text-[10px] font-mono tracking-widest uppercase mt-3 text-[var(--color-text-muted)]">
                ← Arraste para explorar · Toque 2x para confirmar →
              </p>
            </div>

            {/* Navigation */}
            <div className="w-full flex justify-between mt-auto pt-4 border-t border-[var(--color-brand-100)]">
              <button
                onClick={handlePrevQ}
                className="px-6 py-2.5 border border-stone-200 rounded-[4px] font-medium text-stone-600 hover:bg-stone-50 transition-colors"
              >
                ← Anterior
              </button>
              <button
                onClick={handleNextQ}
                disabled={!(future[q.id]?.length > 3)}
                className="px-6 py-2.5 bg-[var(--color-brand-600)] text-white rounded-[4px] font-medium hover:bg-[var(--color-brand-700)] transition-colors disabled:opacity-50"
              >
                {step === 5 ? 'Escrever Carta →' : 'Próxima →'}
              </button>
            </div>
          </motion.div>
        </AnimatePresence>
      </div>
    );
  }

  // ── Step 6: Letter editor ─────────────────────────────────────────────────
  return (
    <div className="flex flex-col min-h-[70vh] max-w-3xl mx-auto w-full">
      <div className="bg-[var(--glass)] border border-[var(--color-brand-200)] rounded-xl p-8 mb-8 flex items-start gap-4">
        <div className="bg-[var(--bg-dark)] p-3 rounded-full text-[var(--color-brand-600)] shrink-0 mt-0.5">
          <Leaf className="w-6 h-6" />
        </div>
        <div>
          <h3 className="font-bold text-[18px] mb-1">Sua Visão Compilada</h3>
          <p className="text-[var(--color-text-muted)] leading-relaxed mb-2">
            Com base nas suas escolhas, montamos sua carta para o futuro. Você pode usá-la como está ou editar livremente antes de concluir.
          </p>
          <span className="inline-flex items-center gap-1 text-xs font-bold px-2.5 py-1 rounded-full bg-[var(--color-brand-100)] text-[var(--color-brand-700)] border border-[var(--color-brand-200)]">
            ● Quando estiver satisfeito com sua carta, clique em "Concluir Jornada"
          </span>
        </div>
      </div>

      <div className="flex-grow flex flex-col">
        <textarea
          value={letter || autoGeneratedLetter}
          onChange={(e) => handleLetterChange(e.target.value)}
          className="flex-grow w-full h-[300px] p-8 bg-[var(--bg-dark)] border border-[var(--color-brand-300)] rounded-xl outline-none focus:border-[var(--color-brand-500)] focus:ring-1 focus:ring-[var(--color-brand-500)] transition-colors resize-none mb-8 text-[var(--text-main)] font-serif leading-relaxed text-lg shadow-inner"
        />
        <div className="mt-auto flex justify-between">
          <button
            onClick={() => { updateMission('mission8', { letter: '' }); setStep(5); }}
            className="px-6 py-2.5 border border-stone-200 rounded-[4px] font-medium text-stone-600 hover:bg-stone-50 transition-colors"
          >
            ← Voltar
          </button>
          <button
            onClick={handleComplete}
            disabled={(letter || autoGeneratedLetter).length < 10}
            className="px-6 py-2.5 bg-[var(--color-brand-600)] text-white rounded-[4px] font-medium hover:bg-[var(--color-brand-700)] transition-colors disabled:opacity-50"
          >
            Concluir a Jornada
          </button>
        </div>
      </div>
    </div>
  );
}
